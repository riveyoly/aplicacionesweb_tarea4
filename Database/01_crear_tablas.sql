-- =====================================================================
--  SISTEMA DE GESTION DE TICKETS - Creacion de tablas (PostgreSQL)
--  5 entidades, cada una con 5 atributos ademas de su identificador.
--  Ejecutar sobre la base "gestion_tickets".
--  En Docker se ejecuta solo la primera vez que arranca el contenedor "db".
-- =====================================================================

-- ---------- 1. categorias ----------
CREATE TABLE categorias (
    categoria_id            integer GENERATED BY DEFAULT AS IDENTITY,
    nombre                  varchar(60)  NOT NULL,
    descripcion             varchar(250),
    prioridad               varchar(10)  NOT NULL,
    tiempo_respuesta_horas  integer      NOT NULL,
    activa                  boolean      NOT NULL,
    CONSTRAINT pk_categorias PRIMARY KEY (categoria_id),
    CONSTRAINT uq_categorias_nombre UNIQUE (nombre),
    CONSTRAINT ck_categorias_prioridad CHECK (prioridad IN ('Baja', 'Media', 'Alta', 'Crítica')),
    CONSTRAINT ck_categorias_tiempo CHECK (tiempo_respuesta_horas BETWEEN 1 AND 720)
);
COMMENT ON TABLE categorias IS 'Tipos de problema que se atienden y su tiempo de respuesta.';

-- ---------- 2. usuarios ----------
CREATE TABLE usuarios (
    usuario_id    integer GENERATED BY DEFAULT AS IDENTITY,
    cedula        varchar(10)  NOT NULL,
    nombre        varchar(100) NOT NULL,
    correo        varchar(120) NOT NULL,
    telefono      varchar(10),
    departamento  varchar(60)  NOT NULL,
    CONSTRAINT pk_usuarios PRIMARY KEY (usuario_id),
    CONSTRAINT uq_usuarios_cedula UNIQUE (cedula),
    CONSTRAINT uq_usuarios_correo UNIQUE (correo),
    CONSTRAINT ck_usuarios_cedula CHECK (cedula ~ '^[0-9]{10}$')
);
COMMENT ON TABLE usuarios IS 'Personas de la empresa que reportan tickets.';

-- ---------- 3. tecnicos ----------
CREATE TABLE tecnicos (
    tecnico_id    integer GENERATED BY DEFAULT AS IDENTITY,
    nombre        varchar(100) NOT NULL,
    correo        varchar(120) NOT NULL,
    telefono      varchar(10),
    especialidad  varchar(80)  NOT NULL,
    activo        boolean      NOT NULL,
    CONSTRAINT pk_tecnicos PRIMARY KEY (tecnico_id),
    CONSTRAINT uq_tecnicos_correo UNIQUE (correo)
);
COMMENT ON TABLE tecnicos IS 'Personal de soporte que atiende los tickets.';

-- ---------- 4. tickets ----------
CREATE TABLE tickets (
    ticket_id       integer GENERATED BY DEFAULT AS IDENTITY,
    asunto          varchar(150)  NOT NULL,
    descripcion     varchar(1000) NOT NULL,
    fecha_apertura  date          NOT NULL,
    usuario_id      integer       NOT NULL,
    categoria_id    integer       NOT NULL,
    CONSTRAINT pk_tickets PRIMARY KEY (ticket_id),
    CONSTRAINT fk_tickets_usuarios FOREIGN KEY (usuario_id)
        REFERENCES usuarios (usuario_id) ON DELETE RESTRICT,
    CONSTRAINT fk_tickets_categorias FOREIGN KEY (categoria_id)
        REFERENCES categorias (categoria_id) ON DELETE RESTRICT
);
CREATE INDEX ix_tickets_usuario_id   ON tickets (usuario_id);
CREATE INDEX ix_tickets_categoria_id ON tickets (categoria_id);
COMMENT ON TABLE tickets IS 'Solicitudes de soporte abiertas por los usuarios.';

-- ---------- 5. seguimientos ----------
CREATE TABLE seguimientos (
    seguimiento_id  integer GENERATED BY DEFAULT AS IDENTITY,
    ticket_id       integer      NOT NULL,
    tecnico_id      integer      NOT NULL,
    fecha           date         NOT NULL,
    estado          varchar(12)  NOT NULL,
    comentario      varchar(500) NOT NULL,
    CONSTRAINT pk_seguimientos PRIMARY KEY (seguimiento_id),
    CONSTRAINT fk_seguimientos_tickets FOREIGN KEY (ticket_id)
        REFERENCES tickets (ticket_id) ON DELETE CASCADE,
    CONSTRAINT fk_seguimientos_tecnicos FOREIGN KEY (tecnico_id)
        REFERENCES tecnicos (tecnico_id) ON DELETE RESTRICT,
    CONSTRAINT ck_seguimientos_estado CHECK (estado IN ('Abierto', 'En proceso', 'Resuelto', 'Cerrado'))
);
CREATE INDEX ix_seguimientos_ticket_id  ON seguimientos (ticket_id);
CREATE INDEX ix_seguimientos_tecnico_id ON seguimientos (tecnico_id);
COMMENT ON TABLE seguimientos IS 'Avances de la atencion de cada ticket; el ultimo define su estado.';
